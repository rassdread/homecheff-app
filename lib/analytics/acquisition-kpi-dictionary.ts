export const SERVICE_MARKETPLACE_CATEGORIES = [
  'ARTISTIC_SERVICE',
  'PRACTICAL_SERVICE',
  'KNOWLEDGE',
] as const;

export function isServiceMarketplaceCategory(value: string | null | undefined): boolean {
  return SERVICE_MARKETPLACE_CATEGORIES.includes(
    value as (typeof SERVICE_MARKETPLACE_CATEGORIES)[number],
  );
}
